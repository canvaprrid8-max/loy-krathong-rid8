-- Supabase SQL setup for the shared Loy Krathong event
create table if not exists public.krathongs (
  id bigint generated by default as identity primary key,
  location_id smallint not null check (location_id between 0 and 3),
  krathong_type smallint not null default 0 check (krathong_type between 0 and 3),
  display_name text not null default 'ผู้ร่วมงาน' check (char_length(display_name) <= 45),
  wish text not null default '' check (char_length(wish) <= 200),
  created_at timestamptz not null default now()
);
alter table public.krathongs enable row level security;
-- Public event: visitors may read public wishes and submit a krathong.
-- For a production public campaign, add CAPTCHA, rate limiting and moderation.
create policy "Anyone can view krathongs"
on public.krathongs for select to anon, authenticated using (true);
create policy "Anyone can submit a krathong"
on public.krathongs for insert to anon, authenticated
with check (
  location_id between 0 and 3
  and krathong_type between 0 and 3
  and char_length(display_name) <= 45
  and char_length(wish) <= 200
);
